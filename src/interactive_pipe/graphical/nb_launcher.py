"""Open a script that asks for the notebook backend in Jupyter.

``python my_script.py -b nb`` from a terminal cannot show ipywidgets: there is
no notebook to draw them in. When the ``nb`` backend starts outside IPython
and the terminal is interactive, the user is offered to write a notebook next
to the script that runs it with the same arguments, and to open it in
Jupyter (JupyterLab, else the classic Notebook) from the same Python
environment, so the kernel finds the same packages.

Declining (or a non-interactive session) keeps the previous behaviour.
Standard library only.
"""

import importlib.util
import json
import shlex
import subprocess
import sys
from pathlib import Path
from typing import Callable, Dict, List, Optional, Sequence

#: Marker in the notebook metadata: a notebook carrying it may be overwritten
NOTEBOOK_MARKER = "interactive_pipe_generated"
#: Jupyter front-ends tried in order, as ``python -m <module>``
JUPYTER_MODULES = ("jupyterlab", "notebook")


def running_in_ipython() -> bool:
    """True inside IPython / a Jupyter kernel."""
    try:
        __IPYTHON__  # type: ignore  # noqa: F821, B018
    except NameError:
        return False
    return True


def script_path(argv0: Optional[str] = None) -> Optional[Path]:
    """The script being run (``sys.argv[0]``), or None for ``python -c`` / an interactive session."""
    raw = sys.argv[0] if argv0 is None else argv0
    if not raw or raw in ("-c", "-"):
        return None
    path = Path(raw)
    if path.suffix != ".py" or not path.is_file():
        return None
    return path.resolve()


def notebook_path_for(script: Path) -> Path:
    """``<script>.ipynb`` next to the script; a notebook not written by us is never overwritten."""
    candidate = script.with_suffix(".ipynb")
    index = 1
    while candidate.exists() and not _is_generated(candidate):
        candidate = script.with_name(f"{script.stem}_interactive_pipe{'' if index == 1 else index}.ipynb")
        index += 1
    return candidate


def _is_generated(path: Path) -> bool:
    try:
        content = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    return bool(isinstance(content, dict) and content.get("metadata", {}).get(NOTEBOOK_MARKER))


def build_notebook(script: Path, arguments: Sequence[str], working_directory: Path) -> Dict:
    """Notebook (nbformat 4) running ``script`` with ``arguments`` from ``working_directory``."""

    def code_cell(source: str) -> Dict:
        return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": source}

    # runpy rather than %run: after a script, %run calls plt.draw(), which adds an empty figure
    # under the sliders (the notebook backend keeps its figure out of pyplot)
    source = "\n".join(
        [
            "%matplotlib inline",
            "import os, runpy, sys",
            f"os.chdir({str(working_directory)!r})",
            f"sys.argv = {[str(script), *arguments]!r}  # as on the command line",
            f"sys.path.insert(0, {str(script.parent)!r})  # like `python script.py`",
            *_library_path_lines(),
            # assigned: as the last expression, the dict of the script's globals would be printed
            'script_globals = runpy.run_path(sys.argv[0], run_name="__main__")',
        ]
    )
    return {
        "cells": [
            {
                "cell_type": "markdown",
                "metadata": {},
                "source": (
                    f"# {script.stem}\n\n"
                    f"Generated by interactive_pipe from `{script.name}`: run the cell below "
                    "(the script is re-executed with the same arguments, the sliders appear under it)."
                ),
            },
            code_cell(source),
        ],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
            NOTEBOOK_MARKER: True,
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def _library_path_lines() -> List[str]:
    """Make the kernel import this interactive_pipe, e.g. a source tree given with PYTHONPATH
    (the kernel may be started without it, by an editor). Nothing for a package in site-packages."""
    import site

    import interactive_pipe

    library_root = Path(interactive_pipe.__file__).resolve().parent.parent
    site_folders = {Path(folder).resolve() for folder in [*site.getsitepackages(), site.getusersitepackages()]}
    if library_root in site_folders:
        return []
    return [f"sys.path.insert(0, {str(library_root)!r})  # the interactive_pipe that wrote this notebook"]


def write_notebook(script: Path, arguments: Sequence[str], working_directory: Optional[Path] = None) -> Path:
    """Write the notebook next to the script and return its path."""
    path = notebook_path_for(script)
    notebook = build_notebook(script, arguments, Path.cwd() if working_directory is None else working_directory)
    path.write_text(json.dumps(notebook, indent=1) + "\n", encoding="utf-8")
    return path


def jupyter_command(notebook: Path) -> Optional[List[str]]:
    """Command opening ``notebook`` with this interpreter's Jupyter, or None when none is installed."""
    for module in JUPYTER_MODULES:
        if importlib.util.find_spec(module) is not None:
            return [sys.executable, "-m", module, str(notebook)]
    return None


def offer_notebook(
    ask: Callable[[str], str] = input,
    launch: Callable[[List[str]], int] = lambda command: subprocess.call(command),
    interactive: Optional[bool] = None,
) -> bool:
    """Offer to generate and open a notebook; returns False when the caller should carry on.

    When the user accepts and Jupyter starts, this does not return: it exits
    with Jupyter's return code once the server stops. When Jupyter is not
    installed, the notebook is written, the command to open it is printed and
    the process exits.
    """
    if running_in_ipython():
        return False
    if interactive is None:
        interactive = sys.stdin.isatty() and sys.stdout.isatty()
    script = script_path()
    if not interactive or script is None:
        return False
    try:
        answer = ask(
            f"The notebook backend (-b nb) needs Jupyter. Generate a notebook for {script.name} and open it? [Y/n] "
        )
    except EOFError:
        return False
    if answer.strip().lower() not in ("", "y", "yes"):
        return False
    notebook = write_notebook(script, sys.argv[1:])
    print(f"Notebook written to {notebook}")
    command = jupyter_command(notebook)
    if command is None:
        print(
            "Jupyter is not installed in this environment. Install it and open the notebook with:\n"
            f"  {shlex.quote(sys.executable)} -m pip install jupyterlab ipywidgets\n"
            f"  {shlex.quote(sys.executable)} -m jupyterlab {shlex.quote(str(notebook))}"
        )
        raise SystemExit(1)
    print("Starting: " + " ".join(shlex.quote(part) for part in command) + "  (Ctrl+C to stop)")
    try:
        code = launch(command)
    except KeyboardInterrupt:
        code = 0
    raise SystemExit(code)
